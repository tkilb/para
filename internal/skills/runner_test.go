func TestInteractiveCmd(t *testing.T) {
	rClaude := Runner{
		Agent:   AgentClaude,
		BinPath: "/bin/claude",
	}
	cmdClaude := rClaude.InteractiveCmd("/tmp/nb", "Initial instructions")
	assert.Equal(t, "/bin/claude", cmdClaude.Path)
	assert.Equal(t, []string{"/bin/claude", "Initial instructions"}, cmdClaude.Args)
	assert.Equal(t, "/tmp/nb", cmdClaude.Dir)

	rAGY := Runner{
		Agent:   AgentAGY,
		BinPath: "/bin/agy",
	}
	cmdAGY := rAGY.InteractiveCmd("/tmp/nb", "Initial instructions")
	assert.Equal(t, "/bin/agy", cmdAGY.Path)
	assert.Equal(t, []string{"/bin/agy", "-i", "Initial instructions"}, cmdAGY.Args)
	assert.Equal(t, "/tmp/nb", cmdAGY.Dir)
}

func TestRunNoteInStoreWithUndoAndCollision(t *testing.T) {
	tempDir := t.TempDir()
	st := store.NewMarkdown(tempDir)

	// Create mock agent script that wraps output in ```markdown fence
	scriptPath := filepath.Join(tempDir, "mock-agent.sh")
	scriptContent := "#!/bin/sh\nprintf '```markdown\\nSummary generated by AI\\n```\\n'\n"
	require.NoError(t, os.WriteFile(scriptPath, []byte(scriptContent), 0o755))

	runner := Runner{
		Agent:   AgentClaude,
		BinPath: scriptPath,
		Timeout: 5 * time.Second,
	}

	// Create a dummy note in projects/alpha/plan.md with specific metadata
	noteDir := filepath.Join(tempDir, "projects", "alpha")
	require.NoError(t, os.MkdirAll(noteDir, 0o755))
	origContent := `---
kind: fact
source: meeting
tags: [project, roadmap]
people: [Alice B.]
---

# Original Plan`
	origNotePath := filepath.Join(noteDir, "plan.md")
	require.NoError(t, os.WriteFile(origNotePath, []byte(origContent), 0o644))

	s := Skill{
		Name: "summarizer",
		Mode: ModeNote,
		Body: "Summarize this note",
	}

	fixedTime := time.Date(2026, 11, 25, 14, 30, 0, 0, time.UTC)
	res, err := runner.RunNoteInStore(context.Background(), st, tempDir, "projects/alpha/plan.md", origContent, s, fixedTime)
	require.NoError(t, err)

	expectedRel := filepath.Join("projects", "alpha", "plan 2026-11-25 14-30-00.md")
	assert.Equal(t, expectedRel, res.Rel)

	fullNewPath := filepath.Join(tempDir, expectedRel)
	require.FileExists(t, fullNewPath)

	data, err := os.ReadFile(fullNewPath)
	require.NoError(t, err)

	parsed := store.ParseNote(filepath.Base(fullNewPath), data)
	assert.Equal(t, "Summary generated by AI\n", parsed.Body)
	assert.Equal(t, "plan 2026-11-25 14-30-00", parsed.Title)
	assert.Equal(t, store.KindFact, parsed.Kind)
	require.NotNil(t, parsed.Frontmatter)
	assert.Equal(t, "meeting", getScalar(parsed.Frontmatter, "source"))
	assert.Equal(t, []string{"project", "roadmap"}, getList(parsed.Frontmatter, "tags"))
	assert.Equal(t, []string{"Alice B."}, getList(parsed.Frontmatter, "people"))
	assert.Empty(t, getList(parsed.Frontmatter, "related"))

	// Running again at the exact same timestamp picks a non-colliding name ("... 2.md")
	res2, err := runner.RunNoteInStore(context.Background(), st, tempDir, "projects/alpha/plan.md", origContent, s, fixedTime)
	require.NoError(t, err)
	assert.Equal(t, filepath.Join("projects", "alpha", "plan 2026-11-25 14-30-00 2.md"), res2.Rel)

	// Undo removes the created note
	require.NotNil(t, res2.Action.Undo)
	require.NoError(t, res2.Action.Undo())
	assert.NoFileExists(t, filepath.Join(tempDir, res2.Rel))
}

func TestAGYDigester(t *testing.T) {
	tempDir := t.TempDir()
	scriptPath := filepath.Join(tempDir, "mock-agy.sh")
	scriptContent := `#!/bin/sh
echo '{"topic":"Architecture Review","source":"meeting","notes":[{"title":"API Design","body":"Use REST.","tags":["api"]}],"actions":[],"facts":[],"conclusions":[],"people":["Tyler K."]}'
`
	require.NoError(t, os.WriteFile(scriptPath, []byte(scriptContent), 0o755))

	d := AGYDigester{
		BinPath: scriptPath,
		Timeout: 5 * time.Second,
		Prompt:  "Import prompt",
		Sources: []string{"adhoc", "meeting"},
	}

	got, err := d.Digest(context.Background(), "Meeting transcript text")
	require.NoError(t, err)
	assert.Equal(t, "Architecture Review", got.Topic)
	assert.Equal(t, "meeting", got.Source)
	require.Len(t, got.Notes, 1)
	assert.Equal(t, "API Design", got.Notes[0].Title)
}
