func TestBuildPromptVsInteractivePrompt(t *testing.T) {
	s := Skill{
		Name: "summarize",
		Body: "Please summarize this document.",
	}
	notePrompt := BuildPrompt(s, "plan.md", "# Project Plan\nDeliver by Q4.")
	assert.Contains(t, notePrompt, "Output ONLY the final note body text.")
	assert.Contains(t, notePrompt, "Please summarize this document.")
	assert.Contains(t, notePrompt, "Note: plan.md")
	assert.Contains(t, notePrompt, "# Project Plan")

	interactivePrompt := BuildInteractivePrompt(s, "projects/alpha/plan.md", "# Project Plan\nDeliver by Q4.")
	assert.NotContains(t, interactivePrompt, "Output ONLY the final note body text.")
	assert.NotContains(t, interactivePrompt, "Do NOT use tools")
	assert.Contains(t, interactivePrompt, "Please summarize this document.")
	assert.Contains(t, interactivePrompt, "Note: projects/alpha/plan.md")
	assert.Contains(t, interactivePrompt, "# Project Plan")
}

